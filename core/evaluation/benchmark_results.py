"""Validation and indexing for committed showcase benchmark results (issue #198).

A published result is a JSON report generated by ``core.evaluation.showcase_report``.
This module enforces the integrity contract before the repo treats it as evidence:

* the report satisfies :func:`check_report`;
* ``provenance.config_sha256`` matches the embedded ``config_snapshot``;
* every dataset ``sha256`` matches the dataset file that is still in the repo;
* the filename ``<YYYY-MM-DD>-<sha>`` agrees with the recorded timestamp and
  git commit.

It also renders the generated ``docs/benchmarks/README.md`` index so the
published tables and links never contain hand-typed numbers.
"""

from __future__ import annotations

import hashlib
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Mapping, Optional, Sequence, Union

from core.evaluation.showcase_report import (
    REPO_ROOT,
    check_report,
    load_report,
)

RESULT_STEM_RE = re.compile(r"^(?P<date>\d{4}-\d{2}-\d{2})-(?P<sha>[0-9a-f]{7,40})$")
REQUIRED_PROVENANCE = (
    "git_sha",
    "timestamp",
    "platform",
    "python_version",
    "seed",
    "config_sha256",
    "config_snapshot",
)
_SIBLING_SUFFIXES = (".md", ".csv", "-pareto.svg", "-latency.svg")


class BenchmarkResultError(ValueError):
    """Raised when a committed result cannot be parsed or discovered."""


def _resolve(path: Union[str, Path], repo_root: Path) -> Path:
    target = Path(path)
    if not target.is_absolute():
        target = repo_root / target
    return target


def _sha256_file(path: Union[str, Path], repo_root: Path) -> str:
    target = _resolve(path, repo_root)
    if not target.exists():
        return ""
    return hashlib.sha256(target.read_bytes()).hexdigest()


def validate_result(
    report: Mapping[str, Any],
    *,
    path: Optional[Union[str, Path]] = None,
    repo_root: Path = REPO_ROOT,
) -> List[str]:
    """Return a list of integrity problems (empty means valid)."""
    problems = list(check_report(report))

    provenance = report.get("provenance") or {}
    if not isinstance(provenance, Mapping):
        return problems + ["provenance must be an object"]
    for key in REQUIRED_PROVENANCE:
        value = provenance.get(key)
        if value is None or (isinstance(value, str) and not value.strip()):
            problems.append(f"provenance.{key} is missing")

    snapshot = provenance.get("config_snapshot")
    config_sha = provenance.get("config_sha256")
    if isinstance(snapshot, str) and snapshot:
        actual = hashlib.sha256(snapshot.encode("utf-8")).hexdigest()
        if actual != config_sha:
            problems.append("provenance.config_sha256 does not match config_snapshot")
    elif "provenance.config_snapshot is missing" not in problems:
        problems.append("provenance.config_snapshot is missing")

    for dataset in report.get("datasets") or []:
        if not isinstance(dataset, Mapping):
            problems.append("datasets entries must be objects")
            continue
        name = dataset.get("name")
        recorded = dataset.get("sha256")
        actual = _sha256_file(str(dataset.get("path") or ""), repo_root)
        if not actual:
            problems.append(f"dataset file is missing: {name} ({dataset.get('path')})")
        elif actual != recorded:
            problems.append(f"dataset hash mismatch: {name}")

    if path is not None:
        stem = Path(path).stem
        match = RESULT_STEM_RE.match(stem)
        if not match:
            problems.append(f"result filename must be <YYYY-MM-DD>-<sha>: {stem}")
        else:
            timestamp = str(provenance.get("timestamp") or "")
            if not timestamp.startswith(match.group("date")):
                problems.append("filename date does not match provenance.timestamp")
            git_sha = str(provenance.get("git_sha") or "")
            if not git_sha.startswith(match.group("sha")):
                problems.append("filename sha does not match provenance.git_sha")

    return problems


@dataclass
class ResultEntry:
    """One discovered result and its sibling artifacts."""

    stem: str
    json_path: Path
    report: Dict[str, Any]
    md_path: Optional[Path] = None
    csv_path: Optional[Path] = None
    svg_paths: List[Path] = field(default_factory=list)
    problems: List[str] = field(default_factory=list)

    @property
    def provenance(self) -> Mapping[str, Any]:
        return self.report.get("provenance") or {}

    @property
    def suite(self) -> Mapping[str, Any]:
        return self.report.get("suite") or {}

    @property
    def dataset_names(self) -> List[str]:
        return [
            str(item.get("name"))
            for item in (self.report.get("datasets") or [])
            if isinstance(item, Mapping)
        ]


def discover_results(
    results_dir: Union[str, Path],
    *,
    repo_root: Path = REPO_ROOT,
) -> Dict[str, Any]:
    """Load every ``*.json`` result, verify it, and flag orphaned siblings."""
    directory = _resolve(results_dir, repo_root)
    entries: List[ResultEntry] = []
    if not directory.exists():
        return {"entries": entries, "orphans": [], "problems": []}

    for json_path in sorted(directory.glob("*.json")):
        try:
            report = load_report(json_path)
        except Exception as exc:  # noqa: BLE001 - surfaced as a validation problem
            entries.append(
                ResultEntry(
                    stem=json_path.stem,
                    json_path=json_path,
                    report={},
                    problems=[f"could not parse report: {exc}"],
                )
            )
            continue
        entry = ResultEntry(
            stem=json_path.stem,
            json_path=json_path,
            report=report,
            md_path=_existing(directory / f"{json_path.stem}.md"),
            csv_path=_existing(directory / f"{json_path.stem}.csv"),
        )
        entry.svg_paths = [
            candidate
            for candidate in (
                _existing(directory / f"{json_path.stem}-pareto.svg"),
                _existing(directory / f"{json_path.stem}-latency.svg"),
            )
            if candidate is not None
        ]
        entry.problems = validate_result(report, path=json_path, repo_root=repo_root)
        entries.append(entry)

    stems = {entry.stem for entry in entries}
    orphans = [
        item
        for item in sorted(directory.iterdir())
        if item.name != "README.md"
        and item.suffix in {".md", ".csv", ".svg"}
        and not any(
            item.name == f"{stem}{suffix}" for stem in stems for suffix in _SIBLING_SUFFIXES
        )
    ]
    problems = [f"{entry.stem}: {problem}" for entry in entries for problem in entry.problems]
    return {"entries": entries, "orphans": orphans, "problems": problems}


def _existing(path: Path) -> Optional[Path]:
    return path if path.exists() else None


def _link(path: Optional[Path]) -> str:
    if path is None:
        return "-"
    return f"[{path.name}](results/{path.name})"


def _recommended_label(report: Mapping[str, Any]) -> str:
    recommendation = report.get("recommended") or {}
    if not isinstance(recommendation, Mapping):
        return "-"
    combo = recommendation.get("combination_id")
    return str(combo) if combo else "-"


def render_results_index(discovered: Mapping[str, Any]) -> str:
    """Render ``docs/benchmarks/README.md`` from discovered results."""
    entries: Sequence[ResultEntry] = discovered.get("entries") or []
    lines: List[str] = [
        "# Benchmark results",
        "",
        "> Generated by `python -m app.benchmark_results` from the reports under",
        "> [`results/`](results/). Do not edit this file by hand: every table entry",
        "> below is derived from a committed JSON report, and `--check` fails if the",
        "> index or an artifact drifts.",
        "",
        "These are reproducible numbers from the reference CPU profile in",
        "[methodology.md](methodology.md), not vendor or production benchmarks.",
        "",
    ]

    if not entries:
        lines.extend(
            [
                "## Published runs",
                "",
                "No benchmark results are committed yet.",
                "",
            ]
        )
    else:
        lines.extend(
            [
                "## Published runs",
                "",
                "| Run | Suite | Generated | Datasets | Combinations | Recommended | Artifacts |",
                "| --- | --- | --- | --- | --- | --- | --- |",
            ]
        )
        for entry in entries:
            provenance = entry.provenance
            suite_name = entry.suite.get("suite") or entry.suite.get("name") or "-"
            timestamp = str(provenance.get("timestamp") or "")
            generated = timestamp[:10] or "-"
            artifacts = [
                _link(entry.json_path),
                _link(entry.md_path),
                _link(entry.csv_path),
            ]
            artifacts.extend(_link(svg) for svg in entry.svg_paths)
            lines.append(
                "| `{stem}` | {suite} | {generated} | {datasets} | {combos} | {rec} | {artifacts} |".format(
                    stem=entry.stem,
                    suite=suite_name,
                    generated=generated,
                    datasets=", ".join(entry.dataset_names) or "-",
                    combos=entry.report.get("num_combinations", "-"),
                    rec=_recommended_label(entry.report),
                    artifacts=" ".join(artifacts),
                )
            )
        lines.append("")

    lines.extend(
        [
            "## Reference load numbers",
            "",
            "Request latency and throughput under concurrency are published separately in",
            "[load.md](load.md) (methodology: [load-methodology.md](load-methodology.md)).",
            "",
            "## Reproduce",
            "",
            "```bash",
            "python -m app.benchmark_report --suite reference --config-dir config \\",
            "    --out docs/benchmarks/results/$(date -u +%F)-<sha>.json \\",
            "    --markdown docs/benchmarks/results/$(date -u +%F)-<sha>.md \\",
            "    --csv docs/benchmarks/results/$(date -u +%F)-<sha>.csv \\",
            "    --svg-dir docs/benchmarks/results",
            "python -m app.benchmark_results --check",
            "```",
            "",
            "The exact datasets, metrics, hardware and caveats are in",
            "[methodology.md](methodology.md).",
            "",
        ]
    )
    return "\n".join(lines)


def index_problems(discovered: Mapping[str, Any]) -> List[str]:
    problems: List[str] = list(discovered.get("problems") or [])
    for orphan in discovered.get("orphans") or []:
        problems.append(f"orphaned artifact without a JSON report: {Path(orphan).name}")
    return problems
